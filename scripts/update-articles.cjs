/* scripts/update-articles.js */
const fs = require('fs');
const path = require('path');
const mammoth = require('mammoth');

const DRAFTS_DIR = path.join(__dirname, '../content/drafts');
const OUTPUT_FILE = path.join(__dirname, '../src/content/articles.js');

// Helper to convert "My Cool Article" to "my-cool-article" for URL
const slugify = (str) => str.toLowerCase().trim().replace(/[^\w\s-]/g, '').replace(/[\s_-]+/g, '-').replace(/^-+|-+$/g, '');

async function convertDocxToHtml(filePath) {
  const result = await mammoth.convertToHtml({ path: filePath });
  return result.value; // Returns clean HTML string
}

async function main() {
  console.log('📖 Scanning drafts folder...');
  
  if (!fs.existsSync(DRAFTS_DIR)) {
    console.log('❌ No content/drafts folder found. Create it and add .docx files.');
    process.exit(1);
  }

  const files = fs.readdirSync(DRAFTS_DIR).filter(f => f.endsWith('.docx'));
  
  if (files.length === 0) {
    console.log('📭 No new .docx files found in content/drafts.');
    process.exit(0);
  }

  const articles = [];

  for (const file of files) {
    // Extract title from filename (remove .docx)
    const title = file.replace('.docx', '');
    const slug = slugify(title);
    const filePath = path.join(DRAFTS_DIR, file);
    
    console.log(`⏳ Converting: ${file}`);

    try {
      const content = await convertDocxToHtml(filePath);
      const date = new Date().toISOString().split('T')[0];

      articles.push({
        slug,
        title,
        date,
        category: "Learning", // You can change this manually later
        image: "/images/cover.png", // Default image
        excerpt: "New article published on DividendBro.", // Add this later in the JS file
        content: content // The HTML from Word
      });

      // Move the processed file to an 'archive' folder so it doesn't re-process
      const archiveDir = path.join(__dirname, '../content/archive');
      if (!fs.existsSync(archiveDir)) fs.mkdirSync(archiveDir);
      fs.renameSync(filePath, path.join(archiveDir, file));
      
      console.log(`✅ Converted: ${title}`);

    } catch (e) {
      console.error(`❌ Failed to convert ${file}:`, e.message);
    }
  }

  if (articles.length === 0) {
    console.log('No articles to update.');
    process.exit(0);
  }

  // Check if existing articles.js exists
  let existingArticles = [];
  if (fs.existsSync(OUTPUT_FILE)) {
    // Simple way to read existing articles: require it, but we need to make it executable
    // Delete cache and require
    delete require.cache[require.resolve(OUTPUT_FILE)];
    try {
      existingArticles = require(OUTPUT_FILE).articles;
    } catch (e) {
      console.error('Could not read existing articles.js. Overwriting with new data.');
    }
  }

  // Merge: New articles first, then existing
  const allArticles = [...articles, ...existingArticles];

  // Generate the JS file content
  const jsContent = `// Auto-generated by scripts/update-articles.js\n// Last updated: ${new Date().toISOString()}\n\nexport const articles = ${JSON.stringify(allArticles, null, 2)};\n`;

  fs.writeFileSync(OUTPUT_FILE, jsContent);
  console.log(`🎉 Success! ${articles.length} new article(s) added to src/content/articles.js`);
}

main();